-- Backfill the FK every earlier migration deferred to "the auth step" (see the comments in V3,
-- V5, V6). ON DELETE CASCADE makes FR-05 (cascading, irreversible account deletion) a single
-- `DELETE FROM app_user` — the database guarantees completeness of the cascade rather than
-- hand-written multi-table deletion code that has to be remembered as the schema grows.
ALTER TABLE pantry_item ADD CONSTRAINT fk_pantry_item_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE;
ALTER TABLE recipe ADD CONSTRAINT fk_recipe_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE;
ALTER TABLE agent_run ADD CONSTRAINT fk_agent_run_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE;
ALTER TABLE cooked_dish ADD CONSTRAINT fk_cooked_dish_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE;

-- tool_call has no user_id of its own — promote its existing FK to agent_run so that deleting
-- an agent_run (via the app_user cascade above) also removes its tool_call rows.
ALTER TABLE tool_call DROP CONSTRAINT tool_call_agent_run_id_fkey;
ALTER TABLE tool_call ADD CONSTRAINT tool_call_agent_run_id_fkey FOREIGN KEY (agent_run_id) REFERENCES agent_run (id) ON DELETE CASCADE;
