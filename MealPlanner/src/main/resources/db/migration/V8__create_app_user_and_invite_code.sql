-- Step 9: authentication, invites (FR-01 to FR-05, NFR-12, NFR-20/20a).
--
-- Named app_user rather than PRD's "user": `user` is a reserved/special word in Postgres (a
-- pseudo-column/function), which would force quoting it everywhere. Same entity, friendlier name.
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_app_user_email UNIQUE (email)
);

-- FR-01: one-time, tied to the account it registers. Stored in plaintext, unlike FR-80a's
-- hashed Telegram binding codes — an invite code isn't proving an existing identity the way a
-- binding code is, it's closer to a coupon; the PRD only asks for hashing on the Telegram side.
-- ON DELETE SET NULL, not CASCADE: an invite code is shared/system-issued infrastructure, not
-- part of the deleted user's own data (FR-05 shouldn't destroy it), so the row survives with
-- used_by_user_id cleared. isUsed() therefore checks used_at, not used_by_user_id — otherwise a
-- code would look unused again (and become reusable) the moment the user who consumed it is
-- deleted, silently reopening exactly what FR-01's one-time-use guarantee exists to prevent.
CREATE TABLE invite_code (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(64) NOT NULL,
    used_by_user_id BIGINT      REFERENCES app_user (id) ON DELETE SET NULL,
    used_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_invite_code_code UNIQUE (code)
);

